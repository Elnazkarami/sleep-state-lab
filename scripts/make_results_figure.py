"""The cohort figure, drawn from saved metrics rather than from memory.

Everything here is read out of ``docs/cohort_metrics.json``, which was itself
generated by ``sleepstatelab report`` from saved per-epoch predictions. Nothing
is typed in. Re-running this after a new evaluation redraws the figure.

Three panels, because three things are worth seeing at once and none of them is
a single headline number:

* what each model scored, with every held-out participant shown as a point --
  the spread between people is larger than the spread between models, and a bar
  chart alone would hide that;
* what the context controls did to the temporal models, which is how we know
  the context is being used at all;
* where the errors sit relative to a stage boundary, which is the finding the
  aggregate numbers cannot show.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
INK = "#1b1b1b"
MUTED = "#8a8a8a"
ACCENT = "#2b6cb0"
WARM = "#b7791f"


def load_metrics() -> dict[str, dict]:
    payload = json.loads((ROOT / "docs" / "cohort_metrics.json").read_text())
    return {entry["model"]: entry for entry in payload}


def transition_bands() -> dict[str, list[float]]:
    """Per-band participant macro-F1 for D1, D2 and D3, from the saved report."""
    text = (ROOT / "docs" / "results_transitions.md").read_text()
    bands = ["at a change", "1 epoch away", "2 epochs away", "3-5 epochs away", "6+ epochs away"]
    out: dict[str, list[float]] = {}
    for model in ("D1", "D2", "D3"):
        marker = f"\n## {model}\n"
        if marker not in text:
            continue
        block = text[text.index(marker) :]
        nxt = block.find("\n## ", 5)
        block = block[:nxt] if nxt > 0 else block
        values = []
        for band in bands:
            row = next((line for line in block.splitlines() if line.startswith(f"| {band} |")), None)
            if row is None:
                values.append(float("nan"))
                continue
            values.append(float(row.split("|")[4].split("±")[0].strip()))
        out[model] = values
    return out


def draw() -> Path:
    metrics = load_metrics()
    figure = plt.figure(figsize=(13.5, 4.6))
    grid = figure.add_gridspec(1, 3, width_ratios=[1.25, 1.0, 1.1], wspace=0.32)

    # --- panel 1: the models, with every participant shown ------------------
    axis = figure.add_subplot(grid[0, 0])
    order = ["D1", "D2", "D3"]
    for position, model in enumerate(order):
        entry = metrics[model]
        people = np.array(list(entry["participant_macro_f1"].values()))
        jitter = (np.random.default_rng(position).random(people.size) - 0.5) * 0.22
        axis.scatter(
            position + jitter, people, s=22, color=MUTED, alpha=0.75, zorder=2,
            label="held-out participant" if position == 0 else None,
        )
        mean = entry["participant_macro_f1_mean"]
        axis.plot([position - 0.3, position + 0.3], [mean, mean], color=ACCENT, lw=2.6, zorder=3)
        axis.annotate(
            f"{mean:.3f}", (position + 0.33, mean), color=ACCENT, fontsize=9,
            va="center", fontweight="bold",
        )
    axis.set_xticks(range(len(order)))
    axis.set_xticklabels(["D1\nepoch CNN", "D2\n+ context", "D3\n+ pretraining"], fontsize=9)
    axis.set_ylabel("participant macro-F1", fontsize=9)
    axis.set_title(
        "Each point is one of 15 held-out participants\n"
        "(full labels; the spread between people exceeds the spread between models)",
        fontsize=9, color=INK,
    )
    axis.legend(fontsize=8, loc="lower left", frameon=False)
    axis.set_ylim(0.45, 0.9)

    # --- panel 2: the context controls --------------------------------------
    axis = figure.add_subplot(grid[0, 1])
    labels, intact, shuffled, masked = [], [], [], []
    for model in ("D2", "D3"):
        labels.append(model)
        intact.append(metrics[model]["participant_macro_f1_mean"])
        shuffled.append(metrics[f"{model}-shuffled-context"]["participant_macro_f1_mean"])
        masked.append(metrics[f"{model}-context-masked"]["participant_macro_f1_mean"])
    x = np.arange(len(labels))
    width = 0.26
    axis.bar(x - width, intact, width, label="intact", color=ACCENT)
    axis.bar(x, shuffled, width, label="neighbours shuffled", color=WARM)
    axis.bar(x + width, masked, width, label="context removed", color=MUTED)
    axis.set_xticks(x)
    axis.set_xticklabels(labels, fontsize=9)
    axis.set_ylabel("participant macro-F1", fontsize=9)
    axis.set_ylim(0.55, 0.78)
    axis.set_title(
        "Removing the context costs more than\nshuffling it: the neighbourhood is read,\nits order barely",
        fontsize=9, color=INK,
    )
    axis.legend(fontsize=8, frameon=False)

    # --- panel 3: distance from a stage change ------------------------------
    axis = figure.add_subplot(grid[0, 2])
    bands = transition_bands()
    names = ["at a\nchange", "1", "2", "3\u20135", "6+"]  # en dash: a range
    for model, colour in (("D1", MUTED), ("D2", ACCENT), ("D3", WARM)):
        if model in bands:
            axis.plot(range(5), bands[model], marker="o", ms=5, lw=2, color=colour, label=model)
    axis.set_xticks(range(5))
    axis.set_xticklabels(names, fontsize=9)
    axis.set_xlabel("epochs from the nearest scored stage change", fontsize=9)
    axis.set_ylabel("participant macro-F1", fontsize=9)
    axis.set_title(
        "At a boundary the three models are\nindistinguishable; context only helps\nonce you are inside a stage",
        fontsize=9, color=INK,
    )
    axis.legend(fontsize=8, frameon=False)

    for ax in figure.axes:
        ax.spines[["top", "right"]].set_visible(False)
        ax.tick_params(labelsize=8.5)
        ax.grid(axis="y", color="#e8e8e8", lw=0.8)
        ax.set_axisbelow(True)

    figure.suptitle(
        "Sleep-EDF Cassette, 78 participants, 15 held out — 81,355 test epochs per model",
        fontsize=10.5, color=INK, y=1.02,
    )
    target = ROOT / "docs" / "results_cohort.png"
    figure.savefig(target, dpi=150, bbox_inches="tight", facecolor="white")
    plt.close(figure)
    return target


if __name__ == "__main__":
    print(f"written to {draw()}")
